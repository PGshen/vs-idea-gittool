// Lists the monochrome IntelliJ icons: light SVGs whose only color is the standard icon gray (#6C707E).
// In the "vscode" appearance these are tinted with --vscode-icon-foreground (see Icon in src/webview/lib/icons.tsx).
// Writes src/webview/lib/monoIcons.ts. Run by scripts/build.mjs.
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = 'media/icons';
const names = [];
const walk = dir => {
  for (const f of readdirSync(join(root, dir)).sort()) {
    const rel = dir ? `${dir}/${f}` : f;
    if (statSync(join(root, rel)).isDirectory()) walk(rel);
    else if (f.endsWith('.svg') && !f.endsWith('_dark.svg')) {
      const svg = readFileSync(join(root, rel), 'utf8');
      const colors = new Set([...svg.matchAll(/(?:fill|stroke|stop-color)\s*[=:]\s*"?\s*(#[0-9a-fA-F]{3,8})/g)].map(m => m[1].toUpperCase()));
      if (colors.size === 1 && colors.has('#6C707E')) names.push(rel.slice(0, -4));
    }
  }
};
walk('');
const out = `// Generated by scripts/gen-mono-icons.mjs. Do not edit.
/** Icons drawn only in the IntelliJ icon gray, tinted with --vscode-icon-foreground in the "vscode" appearance. */
export const MONO_ICONS: ReadonlySet<string> = new Set(${JSON.stringify(names, null, 0).replace(/","/g, '", "')});
`;
let old = '';
try {
  old = readFileSync('src/webview/lib/monoIcons.ts', 'utf8');
} catch {}
if (old !== out) writeFileSync('src/webview/lib/monoIcons.ts', out);
console.log(`mono icons: ${names.length}`);
